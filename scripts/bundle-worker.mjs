// Bundles dist/ into a single self-contained Cloudflare Worker (build/worker.js).
// The whole site is embedded in the script, so deploying = uploading one module
// (works with `wrangler deploy` or a single PUT to the Workers Scripts API).
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, extname } from 'node:path';

const TYPES = {
  '.html': 'text/html; charset=utf-8', '.txt': 'text/plain; charset=utf-8', '.xml': 'application/xml; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json', '.ico': 'image/x-icon', '.webp': 'image/webp', '.jpg': 'image/jpeg',
};
const BINARY = new Set(['.png', '.ico', '.webp', '.jpg']);
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));

const files = {};
for (const f of walk('dist')) {
  if (/(^|[\\/])\./.test(f.slice(5))) continue;
  const ext = extname(f);
  const buf = readFileSync(f);
  const rss = f.endsWith('rss.xml');
  files['/' + f.slice(5).split('\\').join('/')] = {
    t: rss ? 'application/rss+xml; charset=utf-8' : TYPES[ext] || 'application/octet-stream',
    b: BINARY.has(ext) ? 1 : 0,
    c: BINARY.has(ext) ? buf.toString('base64') : buf.toString('utf8'),
    e: '"' + createHash('sha256').update(buf).digest('hex').slice(0, 16) + '"',
  };
}

const worker = `// GENERATED by scripts/bundle-worker.mjs — do not edit. Source: src/, worker logic below.
const APEX = 'appsforbudgeting.com';
const FILES = ${JSON.stringify(files)};
const bin = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
function resolve(p) {
  if (p === '/') return '/index.html';
  if (FILES[p]) return p;
  if (FILES[p + '.html']) return p + '.html';
  if (FILES[p + '/index.html']) return p + '/index.html';
  return null;
}
function respond(key, req, status = 200) {
  const f = FILES[key];
  const h = new Headers({
    'Content-Type': f.t,
    ETag: f.e,
    'Cache-Control': f.t.startsWith('text/html') ? 'public, max-age=0, must-revalidate' : 'public, max-age=3600',
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Strict-Transport-Security': 'max-age=31536000',
  });
  if (status === 200 && req.headers.get('If-None-Match') === f.e) return new Response(null, { status: 304, headers: h });
  const body = req.method === 'HEAD' ? null : f.b ? bin(f.c) : f.c;
  return new Response(body, { status, headers: h });
}
export default {
  async fetch(req) {
    const url = new URL(req.url);
    if (url.hostname !== APEX && url.hostname.endsWith(APEX)) {
      url.hostname = APEX;
      return Response.redirect(url.toString(), 301);
    }
    if (req.method !== 'GET' && req.method !== 'HEAD') return new Response('Method not allowed', { status: 405 });
    let p;
    try { p = decodeURIComponent(url.pathname); } catch { return respond('/404.html', req, 404); }
    // Never serve dotfiles or dot-directories (/.git, /.env, ...), whatever the build contains.
    if (/(^|\\/)\\./.test(p)) return respond('/404.html', req, 404);
    if (p.length > 1 && p.endsWith('/')) { url.pathname = p.replace(/\\/+$/, ''); return Response.redirect(url.toString(), 301); }
    if (p.endsWith('.html')) {
      const clean = p === '/index.html' ? '/' : p.slice(0, -5);
      if (FILES[p] && p !== '/404.html') { url.pathname = clean; return Response.redirect(url.toString(), 301); }
    }
    const key = resolve(p);
    if (key) return respond(key, req);
    return respond('/404.html', req, 404);
  },
};
`;
mkdirSync('build', { recursive: true });
writeFileSync('build/worker.js', worker);

// Connector deploy payload: an async fn for the Cloudflare MCP `execute` tool that PUTs the module.
const cfg = JSON.parse(readFileSync('wrangler.jsonc', 'utf8').replace(/^\s*\/\/.*$/gm, ''));
const metadata = { main_module: 'worker.js', compatibility_date: cfg.compatibility_date, observability: { enabled: true } };
const deploy = `async () => {
  const b = 'F' + Date.now();
  const body = ['--' + b, 'Content-Disposition: form-data; name="metadata"', 'Content-Type: application/json', '', ${JSON.stringify(JSON.stringify(metadata))},
    '--' + b, 'Content-Disposition: form-data; name="worker.js"; filename="worker.js"', 'Content-Type: application/javascript+module', '', ${JSON.stringify(worker)}, '--' + b + '--'].join('\\r\\n');
  const r = await cloudflare.request({ method: 'PUT', path: \`/accounts/\${accountId}/workers/scripts/${cfg.name}\`, body, contentType: 'multipart/form-data; boundary=' + b, rawBody: true });
  return { success: r.success, etag: r.result && r.result.etag, modified_on: r.result && r.result.modified_on, errors: r.errors };
}`;
writeFileSync('build/deploy-via-connector.js', deploy);
console.log(`bundled ${Object.keys(files).length} files -> build/worker.js (${(worker.length / 1024).toFixed(1)} KB)`);
